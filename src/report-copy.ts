export function displayReason(reason: string): string {
  const legal = /^법령 원문 확인 미완료: ([A-Za-z0-9_.:-]+) \(([^()\r\n]+)\)$/u.exec(reason);
  if (legal) return `법령 원문 대조 필요: ${legal[1]} (${legal[2]})`;
  return reasonCopy[reason] ?? reason;
}

/** Host output only; never stage 1 input, names, source quotes or identifiers. */
export function displayGuidanceOutput(text: string): string {
  const hypothesis = /^polymer에 명시된 (PET|HDPE|LDPE|PP|PE|PS|PVC|ABS)이 단일 수지로 확인된다는 가설입니다\. 혼합·층별 분리·라벨 문제는 확인 자료가 필요합니다\.$/u.exec(text);
  if (hypothesis) return hypothesis[1] + "이 단일 수지로 확인된다고 가정했습니다. 혼합·층별 분리·라벨은 자료로 확인하세요.";
  const condition = /^가정별 안내: ([A-Za-z0-9_-]+) \((route-supported|unavailable)\)$/u.exec(text);
  if (condition) return `조건별 안내: ${condition[1]} (${condition[2]})`;
  const comparison = /^실제 비교 출력: ([A-Za-z0-9_-]+)$/u.exec(text);
  if (comparison) return `사례 비교: ${comparison[1]}`;
  return displayReason(text);
}
